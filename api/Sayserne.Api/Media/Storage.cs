namespace Sayserne.Api.Media;

/// <summary>Deploy-time storage configuration (paths and credentials). WHICH provider receives new uploads is the runtime setting Storage.Provider.</summary>
public sealed class StorageOptions
{
    /// <summary>Folder for the "disk" provider. Relative paths are under the application folder.</summary>
    public string DiskPath { get; set; } = "storage";
    public S3Options S3 { get; set; } = new();
}

public sealed class S3Options
{
    /// <summary>Base URL of the object store, e.g. https://s3.eu-central-1.amazonaws.com or https://minio.example.com:9000. Path-style addressing is used.</summary>
    public string Endpoint { get; set; } = "";
    public string Bucket { get; set; } = "";
    public string Region { get; set; } = "us-east-1";
    public string AccessKey { get; set; } = "";
    public string SecretKey { get; set; } = "";
    public bool IsConfigured => Endpoint.Length > 0 && Bucket.Length > 0 && AccessKey.Length > 0 && SecretKey.Length > 0;
}

public sealed class StorageException(string message, Exception? inner = null) : Exception(message, inner);

/// <summary>Keys are always generated by the server (never taken from a user), and are checked again here so a key can never escape its root.</summary>
public static partial class StorageKeys
{
    [GeneratedRegex(@"^[a-z0-9][a-z0-9_\-./]{0,298}[a-z0-9]$")]
    private static partial Regex Pattern();

    public static string Validate(string key) =>
        Pattern().IsMatch(key) && !key.Contains("..", StringComparison.Ordinal) && !key.Contains("//", StringComparison.Ordinal)
            ? key : throw new ArgumentException("Invalid storage key.", nameof(key));

    public static string Incoming(string fileId, string extension) => Validate($"incoming/{fileId}.{extension}");
    public static string Final(string fileId, string extension, DateTime utc) => Validate($"files/{utc:yyyy}/{utc:MM}/{fileId}.{extension}");
}

public interface IFileStorage
{
    string Name { get; }
    Task PutAsync(string key, Stream data, string contentType, CancellationToken ct = default);
    Task<Stream> OpenReadAsync(string key, CancellationToken ct = default);
    Task DeleteAsync(string key, CancellationToken ct = default);
}

/// <summary>Files on this server's disk (the default). Writes go to a temporary name and are renamed, so a reader never sees half a file.</summary>
public sealed class DiskStorage(IOptions<StorageOptions> options, IHostEnvironment env) : IFileStorage
{
    public string Name => "disk";

    private string Root => Path.GetFullPath(Path.IsPathRooted(options.Value.DiskPath) ? options.Value.DiskPath : Path.Combine(env.ContentRootPath, options.Value.DiskPath));

    private string PathFor(string key)
    {
        StorageKeys.Validate(key);
        var root = Root;
        var full = Path.GetFullPath(Path.Combine(root, key));
        if (!full.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.Ordinal)) throw new ArgumentException("Invalid storage key.", nameof(key));
        return full;
    }

    public async Task PutAsync(string key, Stream data, string contentType, CancellationToken ct = default)
    {
        var path = PathFor(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var temp = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            await using (var output = new FileStream(temp, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true)) await data.CopyToAsync(output, ct);
            File.Move(temp, path, overwrite: true);
        }
        finally { if (File.Exists(temp)) File.Delete(temp); }
    }

    public Task<Stream> OpenReadAsync(string key, CancellationToken ct = default)
    {
        try { return Task.FromResult<Stream>(new FileStream(PathFor(key), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true)); }
        catch (FileNotFoundException ex) { throw new StorageException("File not found in storage.", ex); }
        catch (DirectoryNotFoundException ex) { throw new StorageException("File not found in storage.", ex); }
    }

    public Task DeleteAsync(string key, CancellationToken ct = default)
    {
        var path = PathFor(key);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }
}

/// <summary>AWS Signature Version 4. Implemented here (no SDK) so it can be verified against Amazon's published test vectors.</summary>
public static class SigV4
{
    public static string Hex(byte[] bytes) => Convert.ToHexString(bytes).ToLowerInvariant();
    public static string Sha256Hex(byte[] data) => Hex(SHA256.HashData(data));
    private static byte[] Hmac(byte[] key, string data) => HMACSHA256.HashData(key, Encoding.UTF8.GetBytes(data));

    /// <summary>RFC 3986 encoding as S3 wants it for object keys (each path segment encoded once; '/' kept).</summary>
    public static string EncodePath(string path)
    {
        var sb = new StringBuilder();
        foreach (var b in Encoding.UTF8.GetBytes(path))
        {
            var c = (char)b;
            if (c is (>= 'A' and <= 'Z') or (>= 'a' and <= 'z') or (>= '0' and <= '9') or '-' or '_' or '.' or '~' or '/') sb.Append(c);
            else sb.Append('%').Append(b.ToString("X2"));
        }
        return sb.ToString();
    }

    /// <param name="headers">Every header to sign, lower-case names (must include host and x-amz-date).</param>
    public static (string Authorization, string Signature) Authorize(string method, string canonicalUri, string canonicalQuery, IDictionary<string, string> headers,
        string payloadHashHex, string accessKey, string secretKey, string region, string service, string amzDate)
    {
        var sorted = headers.OrderBy(h => h.Key, StringComparer.Ordinal).ToList();
        var signedHeaders = string.Join(";", sorted.Select(h => h.Key));
        var canonicalHeaders = string.Concat(sorted.Select(h => $"{h.Key}:{Regex.Replace(h.Value.Trim(), @"\s+", " ")}\n"));
        var canonicalRequest = string.Join("\n", method, canonicalUri, canonicalQuery, canonicalHeaders, signedHeaders, payloadHashHex);
        var date = amzDate[..8];
        var scope = $"{date}/{region}/{service}/aws4_request";
        var stringToSign = string.Join("\n", "AWS4-HMAC-SHA256", amzDate, scope, Sha256Hex(Encoding.UTF8.GetBytes(canonicalRequest)));
        var key = Hmac(Hmac(Hmac(Hmac(Encoding.UTF8.GetBytes("AWS4" + secretKey), date), region), service), "aws4_request");
        var signature = Hex(HMACSHA256.HashData(key, Encoding.UTF8.GetBytes(stringToSign)));
        return ($"AWS4-HMAC-SHA256 Credential={accessKey}/{scope}, SignedHeaders={signedHeaders}, Signature={signature}", signature);
    }
}

/// <summary>An S3-compatible object store (AWS S3, MinIO, Cloudflare R2, Backblaze B2, DigitalOcean Spaces...). Objects are small (images, short videos), so they are buffered.</summary>
public sealed class S3Storage(IOptions<StorageOptions> options, TimeProvider clock) : IFileStorage, IDisposable
{
    private readonly HttpClient _http = new() { Timeout = TimeSpan.FromMinutes(5) };
    public string Name => "s3";
    private S3Options Cfg => options.Value.S3;

    private HttpRequestMessage Build(HttpMethod method, string key, byte[]? body, string? contentType)
    {
        if (!Cfg.IsConfigured) throw new StorageException("S3 storage is not configured.");
        StorageKeys.Validate(key);
        var path = $"/{Cfg.Bucket}/{key}";
        var uri = new Uri(Cfg.Endpoint.TrimEnd('/') + SigV4.EncodePath(path));
        var amzDate = clock.GetUtcNow().UtcDateTime.ToString("yyyyMMdd'T'HHmmss'Z'");
        var payloadHash = SigV4.Sha256Hex(body ?? []);
        var headers = new Dictionary<string, string> { ["host"] = uri.Authority, ["x-amz-content-sha256"] = payloadHash, ["x-amz-date"] = amzDate };
        var (authorization, _) = SigV4.Authorize(method.Method, uri.AbsolutePath, "", headers, payloadHash, Cfg.AccessKey, Cfg.SecretKey, Cfg.Region, "s3", amzDate);
        var request = new HttpRequestMessage(method, uri);
        request.Headers.TryAddWithoutValidation("x-amz-date", amzDate);
        request.Headers.TryAddWithoutValidation("x-amz-content-sha256", payloadHash);
        request.Headers.TryAddWithoutValidation("Authorization", authorization);
        if (body is not null) { request.Content = new ByteArrayContent(body); request.Content.Headers.TryAddWithoutValidation("Content-Type", contentType ?? "application/octet-stream"); }
        return request;
    }

    private async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken ct)
    {
        try { return await _http.SendAsync(request, HttpCompletionOption.ResponseContentRead, ct); }
        catch (HttpRequestException ex) { throw new StorageException("The object store could not be reached.", ex); }
        catch (TaskCanceledException ex) when (!ct.IsCancellationRequested) { throw new StorageException("The object store timed out.", ex); }
    }

    public async Task PutAsync(string key, Stream data, string contentType, CancellationToken ct = default)
    {
        using var buffer = new MemoryStream();
        await data.CopyToAsync(buffer, ct);
        using var response = await SendAsync(Build(HttpMethod.Put, key, buffer.ToArray(), contentType), ct);
        if (!response.IsSuccessStatusCode) throw new StorageException($"The object store refused the upload ({(int)response.StatusCode}).");
    }

    public async Task<Stream> OpenReadAsync(string key, CancellationToken ct = default)
    {
        using var response = await SendAsync(Build(HttpMethod.Get, key, null, null), ct);
        if (response.StatusCode == HttpStatusCode.NotFound) throw new StorageException("File not found in storage.");
        if (!response.IsSuccessStatusCode) throw new StorageException($"The object store refused the download ({(int)response.StatusCode}).");
        return new MemoryStream(await response.Content.ReadAsByteArrayAsync(ct), writable: false);
    }

    public async Task DeleteAsync(string key, CancellationToken ct = default)
    {
        using var response = await SendAsync(Build(HttpMethod.Delete, key, null, null), ct);
        if (!response.IsSuccessStatusCode && response.StatusCode != HttpStatusCode.NotFound) throw new StorageException($"The object store refused the delete ({(int)response.StatusCode}).");
    }

    public void Dispose() => _http.Dispose();
}

public interface IStorageRouter
{
    /// <summary>The provider that receives NEW uploads (runtime setting Storage.Provider).</summary>
    IFileStorage ForWrite();
    /// <summary>The provider a given file was stored with (recorded per file, so switching providers never strands old files).</summary>
    IFileStorage For(string provider);
}

public sealed class StorageRouter(DiskStorage disk, S3Storage s3, ISettingsService settings, IOptions<StorageOptions> options) : IStorageRouter
{
    public IFileStorage ForWrite() => For(settings.GetString("Storage.Provider"));
    public IFileStorage For(string provider) => provider switch
    {
        "disk" => disk,
        "s3" => options.Value.S3.IsConfigured ? s3 : throw new AppException("STORAGE_UNAVAILABLE", 503),
        _ => throw new AppException("STORAGE_UNAVAILABLE", 503),
    };
}
