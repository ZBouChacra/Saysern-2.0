#!/usr/bin/env python3
"""Builds db/migrations/R__ui_texts.sql from the English phrases used in the code and their Arabic translations.

  python3 db/tools/gen_ui_texts.py

The site shows the English phrase when no text is stored for it, so English always works. This file stores BOTH languages as "ui:<phrase>" texts so an admin can
reword or translate any phrase in the back office (Texts). Re-running the migration never overwrites a text an admin has edited: it only refreshes the ones still
equal to their original (default) value. To add a phrase: write it with t("...") in the code, add its Arabic to the matching ui_ar_*.json, run this script."""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ui_keys import ui_key

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = [("web", os.path.join(HERE, "ui_ar_web.json")), ("admin", os.path.join(HERE, "ui_ar_admin.json"))]
OUT = os.path.join(HERE, "..", "migrations", "R__ui_texts.sql")

def q(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"

def main() -> int:
    rows: list[tuple[str, str, str]] = []
    seen: set[str] = set()
    for _name, path in SOURCES:
        if not os.path.exists(path):
            continue
        for english, arabic in json.load(open(path, encoding="utf-8")).items():
            if english in seen:
                continue
            seen.add(english)
            rows += [("en", ui_key(english), english), ("ar", ui_key(english), arabic)]
    lines = ["-- GENERATED by db/tools/gen_ui_texts.py: do not edit by hand (edit the ui_ar_*.json files and run the script).",
             "-- Texts an admin has changed in the back office are never overwritten: only texts still equal to their original value are refreshed.", "",
             "INSERT INTO translations (language, translation_key, value, default_value) VALUES"]
    lines.append(",\n".join(f"({q(l)},{q(k)},{q(v)},{q(v)})" for l, k, v in rows))
    lines.append("ON DUPLICATE KEY UPDATE value = IF(value = default_value, VALUES(value), value), default_value = VALUES(default_value);")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{len(rows) // 2} phrases -> {os.path.normpath(OUT)}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
